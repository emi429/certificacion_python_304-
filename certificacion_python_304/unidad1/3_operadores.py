#operadores relacionales
a=10
b=5
#menore que (<)
resultado=a<b
print(resultado)
#mayor que (>)
resultado=a>b
print(resultado)
#diferente que(!=)
resultado=a!=b
print(resultado)
#igual que(==)
resultado=a==b
print(resultado)
#menor o igual que(<=)
resultado=a<=b
print(resultado)
#mayor o igual que(>=)
resultado=a>=b
print(resultado)
